<#
.SYNOPSIS
    Writes the resource script that embeds the setup payload.

.DESCRIPTION
    OpenA2dpSetup.exe is self-contained: the driver package, the encoder service and the tools
    are compiled in as RCDATA resources. This script runs before ResourceCompile and writes the
    resource lines from the build outputs named on the command line. It fails when a component
    was not built, so an incomplete setup executable is never linked.
#>
param(
    [Parameter(Mandatory)][string]$OutDir,
    [Parameter(Mandatory)][string]$Output
)

$ErrorActionPreference = 'Stop'

$files = [ordered]@{
    'IDR_PAYLOAD_SYS'     = Join-Path $OutDir 'OpenA2dp\OpenA2dp.sys'
    'IDR_PAYLOAD_INF'     = Join-Path $OutDir 'OpenA2dp\OpenA2dp.inf'
    'IDR_PAYLOAD_CAT'     = Join-Path $OutDir 'OpenA2dp\OpenA2dp.cat'
    'IDR_PAYLOAD_SERVICE' = Join-Path $OutDir 'OpenA2dpSvc.exe'
    'IDR_PAYLOAD_CONTROL' = Join-Path $OutDir 'OpenA2dpCtl.exe'
    'IDR_PAYLOAD_CONFIG'  = Join-Path $OutDir 'OpenA2dpConfig.exe'
}

$lines = @(
    '#include "SetupResources.h"',
    '// Generated by scripts/generate-setup-payload.ps1. Do not edit.'
)
foreach ($entry in $files.GetEnumerator())
{
    if (-not (Test-Path -LiteralPath $entry.Value -PathType Leaf))
    {
        throw "Missing setup payload $($entry.Value). Build the driver, service and tools first."
    }
    $path = (Resolve-Path -LiteralPath $entry.Value).Path.Replace('\', '\\')
    $lines += "$($entry.Key) RCDATA `"$path`""
}

$directory = Split-Path -Parent $Output
if ($directory)
{
    New-Item -ItemType Directory -Force -Path $directory | Out-Null
}
Set-Content -LiteralPath $Output -Value $lines -Encoding Ascii
